#include "vedam_config.h"

#include <gtest/gtest.h>

TEST(Config, Basic)
{
#if VEDAM_NODE_CLASS_A
    EXPECT_EQ(VEDAM_NODE_CLASS, 1);
    EXPECT_EQ(VEDAM_ENABLE_MQ, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC_UDS, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONNECT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT_ENGINE, 0);
    EXPECT_EQ(VEDAM_ENABLE_PLUGIN, 1);
    EXPECT_EQ(VEDAM_ENABLE_WWLOCK, 1);
    EXPECT_EQ(VEDAM_BUILD_VEDAMD, 1);
#elif VEDAM_NODE_CLASS_B
    EXPECT_EQ(VEDAM_NODE_CLASS, 2);
    EXPECT_EQ(VEDAM_ENABLE_MQ, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC_UDS, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONNECT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT_ENGINE, 0);
    EXPECT_EQ(VEDAM_ENABLE_PLUGIN, 1);
    EXPECT_EQ(VEDAM_ENABLE_WWLOCK, 1);
    EXPECT_EQ(VEDAM_BUILD_VEDAMD, 1);
#elif VEDAM_NODE_CLASS_C
    EXPECT_EQ(VEDAM_NODE_CLASS, 3);
    EXPECT_EQ(VEDAM_ENABLE_MQ, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC, 1);
    EXPECT_EQ(VEDAM_ENABLE_GRPC_UDS, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONNECT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT_ENGINE, 0);
    EXPECT_EQ(VEDAM_ENABLE_PLUGIN, 0);
    EXPECT_EQ(VEDAM_ENABLE_WWLOCK, 1);
    EXPECT_EQ(VEDAM_BUILD_VEDAMD, 1);
#elif VEDAM_NODE_CLASS_D
    EXPECT_EQ(VEDAM_NODE_CLASS, 4);
    EXPECT_EQ(VEDAM_ENABLE_MQ, 0);
    EXPECT_EQ(VEDAM_ENABLE_GRPC, 0);
    EXPECT_EQ(VEDAM_ENABLE_GRPC_UDS, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONNECT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT_ENGINE, 0);
    EXPECT_EQ(VEDAM_ENABLE_PLUGIN, 0);
    EXPECT_EQ(VEDAM_ENABLE_WWLOCK, 1);
    EXPECT_EQ(VEDAM_BUILD_VEDAMD, 1);
#elif VEDAM_NODE_CLASS_E
    EXPECT_EQ(VEDAM_NODE_CLASS, 5);
    EXPECT_EQ(VEDAM_ENABLE_MQ, 0);
    EXPECT_EQ(VEDAM_ENABLE_GRPC, 0);
    EXPECT_EQ(VEDAM_ENABLE_GRPC_UDS, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONNECT, 0);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT, 1);
    EXPECT_EQ(VEDAM_ENABLE_CONTRACT_ENGINE, 0);
    EXPECT_EQ(VEDAM_ENABLE_PLUGIN, 0);
    EXPECT_EQ(VEDAM_ENABLE_WWLOCK, 0);
    EXPECT_EQ(VEDAM_BUILD_VEDAMD, 0);
#else
    ADD_FAILURE() << "VEDAM_NODE_CLASS letter is not defined";
#endif
}
